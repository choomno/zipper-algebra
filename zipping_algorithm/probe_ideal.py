"""
Architecture probe. The whole harness design turns on ONE question:

    Is each rewrite an exact identity in R B_n, or only an identity in Z_n = R B_n / I?

If exact in R B_n, `evaluate` just compares Artin canonical keys (cheap, what the handoff says).
If only in Z_n, `evaluate` must reduce modulo the two-sided ideal I generated by zipper relators.

We test three things:
  (1) Is zip_relator(n,i,j) itself == 0 in R B_n?   (if yes, I is trivial -> everything exact)
  (2) Are the i=1 foe-removal rules (thesis 812-816, with D1 correction) exact in R B_n?
  (3) Is a corrected higher foe-removal defect a *word-multiple of the relator* (=> in I, not 0)?
"""
import zip_lib as Z
from zip_lib import E, X, zip_relator, w_v, w_vb, w_vinv, w_vbinv, F, qp, ONE

def show(label, elt):
    print(f"  {label}: nterms={elt.nterms()}  iszero={elt.iszero()}")

print("=== (1) Is the shifted zipper relator zero in R B_n? ===")
for (n, i, j) in [(3,2,1), (4,2,1), (4,2,2), (4,3,1), (5,3,1), (5,3,2), (6,4,1)]:
    r = zip_relator(n, i, j)
    print(f"  n={n} i={i} j={j}: relator iszero in RB_n = {r.iszero()}  (nterms={r.nterms()})")

print()
print("=== (2) i=1 foe-removal exact in R B_n?  (X_{1,j} |-> 1) ===")
# thesis 812: sigma_{j-1}(X_{1,j}| -> -(X_{2,j-1}||) + q sigma_{j-1}^{-1}(X_{1,j}||) + (1-q)(X_{1,j}||)
# eps: X_{1,j}->1, delimiters->1. LHS eps = sigma_{j-1}. RHS eps = -X_{2,j-1} + q s_{j-1}^{-1} + (1-q).
n, j = 4, 3
lhs = E(n, (j-1,))
rhs = (-X(n, 2, j-1)) + E(n, (-(j-1),), qp(1)) + E(n, (), ONE - qp(1))
show("812 sigma_{j-1}: LHS-RHS", lhs - rhs)

# thesis 814 WITH D1 correction: sigma_{j-1}^{-1}(X_{1,j}| ->
#   q^{-1}(X_{2,j-1}||) + q^{-1} sigma_{j-1}(X_{1,j}| - q^{-1}(1-q)(X_{1,j}||)
lhs = E(n, (-(j-1),))
rhs = (X(n, 2, j-1)).scale(qp(-1)) + E(n, (j-1,), qp(-1)) - (E(n, (), ONE - qp(1))).scale(qp(-1))
show("814 sigma_{j-1}^{-1} (D1-corrected): LHS-RHS", lhs - rhs)

# same rule with the PRINTED (buggy) middle term sigma_j instead of sigma_{j-1}
rhs_bug = (X(n, 2, j-1)).scale(qp(-1)) + E(n, (j,), qp(-1)) - (E(n, (), ONE - qp(1))).scale(qp(-1))
show("814 PRINTED (buggy) sigma_j: LHS-RHS (should be nonzero)", lhs - rhs_bug)

print()
print("=== (3) higher foe-removal (iii.b^-, D2-corrected): defect = word-multiple of relator? ===")
# corrected bracket:  (-q^{i-1} vbar_{i,j} + v_{i,j} + q^{i-1} vbar_{i-1,j+1}) X_{i,j}
# The claim (D2): sigma_j^{-1}(F X_{i,j}| - RHS  ==  -(sigma_j^{-1} F_{i,j+1,k-1}) * Z_{i,j}
# We just check the bracket identity that underlies it: solving the relator for vs_{i-1,j+1} X_{i,j}.
for (n, i, j) in [(5,3,1), (6,3,2), (6,4,1)]:
    r = zip_relator(n, i, j)
    # relator = (q^{i-1} vbar_{i-1,j+1} - v_{i-1,j+1})X_{i,j} - (q^{i-1} vbar_{i,j} - v_{i,j})X_{i,j}
    # => v_{i-1,j+1} X_{i,j} = (q^{i-1}vbar_{i-1,j+1} - q^{i-1}vbar_{i,j} + v_{i,j})X_{i,j}  (mod relator)
    lhs = E(n, w_v(i-1, j+1)) * X(n, i, j)
    rhs = (E(n, w_vb(i-1, j+1), qp(i-1)) - E(n, w_vb(i, j), qp(i-1)) + E(n, w_v(i, j))) * X(n, i, j)
    diff = lhs - rhs
    # diff should equal +/- the relator (a specific nonzero elt), i.e. diff - (+/-)relator == 0
    print(f"  n={n} i={i} j={j}: (lhs-rhs) == relator? {(diff - r).iszero()}   == -relator? {(diff + r).iszero()}   relator_zero? {r.iszero()}")
