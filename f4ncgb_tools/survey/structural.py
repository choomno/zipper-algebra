"""Structural (non-)semisimplicity, scaling to all n without a trace form.

SEMISIMPLE (linear, framing): the trace form has full rank at one generic point ⟹ (rank is
lower-semicontinuous in (q,t) and can only drop mod p) full generic rank ⟹ generically semisimple.
So a single full-rank point-check CERTIFIES semisimplicity (see semisimple.py).

NON-SEMISIMPLE (jordan): (σ−t)²X₂ = (σ−t)·[(σ−t)X₂] ⟹ I_jordan ⊆ I_linear ⟹ a canonical surjection
π: A_jordan ↠ A_linear.  Char 0: rad(A_jordan) ⊆ ker π (since A_jordan/ker π = A_linear is
semisimple) and ker π ⊆ rad iff ker π is a NILPOTENT ideal.  We compute ker π (= nullspace of the
"reduce mod I_linear" map on the A_jordan basis) and its nilpotency index; if (ker π)^k = 0 then
rad(A_jordan) = ker π and  radical dim = dim(A_jordan) − dim(A_linear)  — at EVERY level n.
"""
from __future__ import annotations
from .spec import Spec
from .pointalg import PointAlgebra


def _nullspace_cols_Fp(M, ncol, p):
    """Right null space of a matrix given as a dict {(row,col): val}; returns list of basis vectors
    (each a dict col->val) over F_p."""
    # dense rows keyed by row index
    rows = {}
    for (r, c), v in M.items():
        rows.setdefault(r, {})[c] = v % p
    A = [rows.get(r, {}) for r in range(max((r for r, _ in M), default=-1) + 1)]
    # Gaussian elimination (row echelon), track pivot columns
    pivot_col = {}
    r = 0
    dense = [[row.get(c, 0) for c in range(ncol)] for row in A]
    nr = len(dense)
    for c in range(ncol):
        piv = next((i for i in range(r, nr) if dense[i][c] % p), None)
        if piv is None:
            continue
        dense[r], dense[piv] = dense[piv], dense[r]
        inv = pow(dense[r][c], p - 2, p)
        dense[r] = [(x * inv) % p for x in dense[r]]
        for i in range(nr):
            if i != r and dense[i][c] % p:
                f = dense[i][c]
                dense[i] = [(dense[i][j] - f * dense[r][j]) % p for j in range(ncol)]
        pivot_col[c] = r
        r += 1
        if r == nr:
            break
    free = [c for c in range(ncol) if c not in pivot_col]
    basis = []
    for fc in free:
        vec = {fc: 1}
        for c, pr in pivot_col.items():
            val = (-dense[pr][fc]) % p
            if val:
                vec[c] = val
        basis.append(vec)
    return basis


