def pi_kernel_nilpotency(n: int, q: int, t: int, scratch: str, char: int, log=print):
    """ker π ⊆ A_jordan and its nilpotency, at (q,t) over F_char. ker π is the two-sided ideal
    generated by the linear untwistings e_i=(x_i−t)(q·y_i+(1−q)−x_i); (ker π)²=0 iff e_i·m·e_j=0 in
    A_jordan for all i,j∈{1..n−1} and basis monomials m (only (n−1)²·dim reductions)."""
    p = char
    Aj = PointAlgebra(Spec("jordan", n), q, t, scratch, char)
    Al = PointAlgebra(Spec("linear", n), q, t, scratch, char)
    dj, dl = Aj.dim, Al.dim
    # dim ker π = nullity of "reduce mod I_linear" on the A_jordan basis (sanity / radical dim)
    M = {}
    for j, b in enumerate(Aj.standard):
        for ii, c in Al.nf(b).items():
            M[(ii, j)] = c % p
    ker = _nullspace_cols_Fp(M, dj, p)
    log(f"[struct n={n}] dim A_jordan={dj}, dim A_linear={dl}, dim ker π={len(ker)} (expect {dj-dl})")
    assert len(ker) == dj - dl, "ker π dim != dim_jordan - dim_linear"

    def e_poly(i):  # e_i as free-algebra poly (dict word->coeff mod p)
        x, y = f"x{i}", f"y{i}"
        X2 = {(y,): q % p, (): (1 - q) % p, (x,): (-1) % p}
        pre = {(x,): 1, (): (-t) % p}  # (x_i − t)
        out = {}
        for wp, cp in pre.items():
            for w2, c2 in X2.items():
                w = wp + w2; out[w] = (out.get(w, 0) + cp * c2) % p
                if not out[w]: del out[w]
        return out

    es = {i: e_poly(i) for i in range(1, n)}
    # sanity: each e_i is 0 mod I_linear (in ker π) and nonzero mod I_jordan
    for i, e in es.items():
        vlin = {}
        for w, c in e.items():
            for k, ck in Al.nf(w).items(): vlin[k] = (vlin.get(k, 0) + c * ck) % p
        assert not any(v % p for v in vlin.values()), f"e_{i} not in ker π (nonzero mod linear)"

    # (ker π)^2 = 0  iff  e_i · m · e_j = 0 in A_jordan for all i,j, basis monomial m
    def nf_poly_word(poly, mid_word, poly2):
        out = {}
        for w1, c1 in poly.items():
            for w2, c2 in poly2.items():
                for k, ck in Aj.nf(w1 + mid_word + w2).items():
                    out[k] = (out.get(k, 0) + c1 * c2 * ck) % p
                    if not out[k]: del out[k]
        return out

    nonzero_pairs = 0
    checked = 0
    for i in es:
        for j in es:
            for m in Aj.standard:
                r = nf_poly_word(es[i], m, es[j]); checked += 1
                if any(v % p for v in r.values()):
                    nonzero_pairs += 1
    nilpotent2 = (nonzero_pairs == 0)
    log(f"[struct n={n}] checked {checked} products e_i·m·e_j; nonzero: {nonzero_pairs} "
        f"=> (ker π)^2 = 0: {nilpotent2}")
    return {"n": n, "dim_jordan": dj, "dim_linear": dl, "ker_dim": len(ker),
            "radical_dim": dj - dl, "nilpotency_index_2": nilpotent2,
            "certifies_rad_eq_ker": nilpotent2, "products_checked": checked}
