#!/usr/bin/env python3
"""
Necessary condition for non-semisimplicity: probe whether X_3 = S[3][1] is
nilpotent in the variant zipper quotient.

  If X_3 != 0 in the quotient and X_3^k = 0 for some k >= 2, then X_3 is a
  nonzero nilpotent in the algebra, so X_3 lies in the Jacobson radical J(A),
  so A is NOT semisimple.

  Note this is one-directional: X_3 not nilpotent does NOT prove A semisimple
  (the radical may be generated by other elements). It is a SMOKING GUN test
  for non-semisimplicity.

Pipeline:
  1. Parse the .basis file.
  2. Build standard-monomial basis via Aho-Corasick (as in compute_dim_aho.py).
  3. Build the slider X_3 = S[3][1] as a free-algebra polynomial from
     scratch (replicating zipper_in_ms.py's S recursion).
  4. Reduce X_3 to standard basis -> vector v in F_p^N.
  5. Compute v^2 by left-multiplying v by itself: for each pair of terms,
     reduce the product and accumulate. Continue v^3, v^4, ...
  6. Report (X_3, X_3^2, X_3^3, ...) and verdict.
"""
from __future__ import annotations
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

# Reuse machinery from semisimple_check.py
from semisimple_check import (
    parse_basis_full, collect_variables, build_aho_corasick,
    enumerate_standard_monomials, find_leading_match,
)


def reduce_to_basis(word_terms, mon_idx, lm_to_tail, ac_delta, ac_is_match,
                    ac_match_pat, p):
    """Reduce list of (coef, mon_tuple) to coef vector dict {idx: coef}."""
    out = {}
    worklist = list(word_terms)
    while worklist:
        coef, word = worklist.pop()
        if coef == 0:
            continue
        if word in mon_idx:
            k = mon_idx[word]
            out[k] = (out.get(k, 0) + coef) % p
            if out[k] == 0:
                del out[k]
            continue
        m = find_leading_match(word, ac_delta, ac_is_match, ac_match_pat)
        if m is None:
            raise RuntimeError(f"Standard word {word} not in basis. "
                               f"Possible incomplete GB or AC bug.")
        start, end, lm = m
        u, v = word[:start], word[end:]
        for c, t_mon in lm_to_tail[lm]:
            worklist.append(((coef * c) % p, u + t_mon + v))
    return out


def build_X3(n, q_int, t_int, p):
    """Build S[3][1] = X_3 as a list of (coef, mon_tuple) terms.

    Replicates the recursion in zipper_in_ms.py:
      S[2][j] = q*y_j + (1-q) - x_j
      S[i][j] = (q^{i-1} y_j y_{j+1} ... y_{j+i-2}
                 - x_j x_{j+1} ... x_{j+i-2}) * S[i-1][j]
    Specialized at (q, t) = (q_int, t_int) in F_p.
    """
    # S[2][1] = q*y_1 + (1-q) - x_1
    S2 = [(q_int % p, ('y1',)),
          ((1 - q_int) % p, ()),
          ((-1) % p, ('x1',))]
    # Multiply on left by (q^2 * y_1*y_2 - x_1*x_2)
    multiplier = [(q_int * q_int % p, ('y1', 'y2')),
                  ((-1) % p, ('x1', 'x2'))]
    # S[3][1] = multiplier * S[2][1]
    S3 = []
    for c1, m1 in multiplier:
        for c2, m2 in S2:
            S3.append(((c1 * c2) % p, m1 + m2))
    return S3


def multiply_vec(v, w, standard, mon_idx, lm_to_tail, ac_delta, ac_is_match,
                 ac_match_pat, p):
    """Compute v * w as a vector in standard basis. v, w are dicts {idx: coef}."""
    result = {}
    for i, ci in v.items():
        for j, cj in w.items():
            if ci == 0 or cj == 0:
                continue
            word = standard[i] + standard[j]
            red = reduce_to_basis([((ci * cj) % p, word)], mon_idx, lm_to_tail,
                                  ac_delta, ac_is_match, ac_match_pat, p)
            for k, c in red.items():
                result[k] = (result.get(k, 0) + c) % p
                if result[k] == 0:
                    del result[k]
    return result


def vec_str(v, standard, max_terms=6):
    if not v:
        return "0"
    items = sorted(v.items(), key=lambda kc: (len(standard[kc[0]]), standard[kc[0]]))
    parts = []
    for k, c in items[:max_terms]:
        mon = "*".join(standard[k]) if standard[k] else "1"
        parts.append(f"{c}*{mon}")
    if len(items) > max_terms:
        parts.append(f"... ({len(items) - max_terms} more)")
    return " + ".join(parts) if parts else "0"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("basis", help="path to f4ncgb basis file")
    ap.add_argument("--n", type=int, required=True, help="strand count")
    ap.add_argument("--q", type=int, default=5)
    ap.add_argument("--t", type=int, default=7)
    ap.add_argument("--char", type=int, default=2147483647)
    ap.add_argument("--max-power", type=int, default=8,
                    help="max k to check X_3^k")
    ap.add_argument("--max-dim", type=int, default=5000)
    args = ap.parse_args()
    p = args.char

    polys = parse_basis_full(args.basis)
    print(f"[parse] {len(polys)} basis polynomials.")
    variables = collect_variables(polys)
    print(f"[vars] {variables}")

    lms = [lm for lm, _ in polys]
    ac_delta, ac_is_match, ac_match_pat, _ = build_aho_corasick(lms, variables)
    standard = enumerate_standard_monomials(ac_delta, ac_is_match, None, variables,
                                            max_total=args.max_dim)
    if standard is None:
        print(f"[abort] dim > {args.max_dim}")
        return 1
    N = len(standard)
    print(f"[dim] N = {N}")

    lm_to_tail = {}
    for lm, terms in polys:
        lead = terms[0][0]
        inv = pow(lead, p - 2, p)
        lm_to_tail[lm] = [((-c * inv) % p, mon) for c, mon in terms[1:]]
    mon_idx = {mon: i for i, mon in enumerate(standard)}

    X3_poly = build_X3(args.n, args.q, args.t, p)
    print(f"[X_3] {len(X3_poly)} terms in the free algebra (before reduction).")

    v = reduce_to_basis(X3_poly, mon_idx, lm_to_tail, ac_delta, ac_is_match,
                        ac_match_pat, p)
    print(f"\nX_3       = {vec_str(v, standard)}  [supp={len(v)}]")

    powers = [v]
    cur = v
    for k in range(2, args.max_power + 1):
        cur = multiply_vec(cur, v, standard, mon_idx, lm_to_tail,
                           ac_delta, ac_is_match, ac_match_pat, p)
        powers.append(cur)
        print(f"X_3^{k:<3}   = {vec_str(cur, standard)}  [supp={len(cur)}]")
        if len(cur) == 0:
            print(f"\n[VERDICT] X_3 is NILPOTENT of index <= {k}.")
            if len(v) == 0:
                print(f"          But X_3 = 0 already (the BMW degeneration), so")
                print(f"          this is the canonical case; nothing new.")
                return 0
            print(f"          X_3 != 0 and X_3^{k} = 0:")
            print(f"          X_3 lies in J(A); the algebra is NON-SEMISIMPLE.")
            return 0
    if len(v) == 0:
        print(f"\n[VERDICT] X_3 = 0 (BMW degeneration).")
    else:
        print(f"\n[VERDICT] X_3^{args.max_power} != 0; X_3 is not nilpotent within")
        print(f"          this power bound. Inconclusive about semisimplicity")
        print(f"          (the algebra may still be non-semisimple via a different")
        print(f"          nilpotent element).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
