"""Regression tests for the f4ncgb_tools pipeline.

Each test fixes a published numerical fact about one of the variant zipper
algebras and verifies that the corresponding script reproduces it. The
intent is to pin current behaviour during refactors; any change in the
core utilities that breaks one of these is caught immediately.

Run with::

    python3 -m f4ncgb_tools.tests       # if invoked as a module
    python3 f4ncgb_tools/tests.py        # standalone

The tests need precomputed ``.basis`` files; they are regenerated by the
fixture-setup step on first run (about 30 seconds total).
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from fractions import Fraction

# Allow running both as a module and as a standalone script.
HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import core  # noqa: E402

F4NCGB = "/home/choom/src/f4ncgb/build-release/f4ncgb"
P_DEFAULT = 2147483647
EMIT = os.path.join(HERE, "zipper_in_ms.py")


def _emit_and_gb(
    workdir: str,
    *,
    n: int,
    untwist: str = "bigelow",
    framing_power: int = 1,
    theta_power: int = 1,
    char: int = P_DEFAULT,
    maxiter: int = 500,
) -> str:
    """Generate the .ms file for the requested variant, run f4ncgb, return the
    .basis path inside ``workdir``."""
    tag = f"n{n}_{untwist}_a{framing_power}_k{theta_power}_char{char}"
    ms = os.path.join(workdir, f"{tag}.ms")
    basis = os.path.join(workdir, f"{tag}.basis")
    subprocess.check_call([
        "python3", EMIT,
        "--n", str(n), "--q", "5", "--t", "7", "--char", str(char),
        "--untwist", untwist,
        "--framing-power", str(framing_power),
        "--theta-power", str(theta_power),
        "--out", ms,
    ], stdout=subprocess.DEVNULL)
    subprocess.check_call(
        [F4NCGB, "--maxiter", str(maxiter), "-o", basis, ms],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    return basis


# --- Module-level fixture: build small basis files once. --------------------

class _Fixtures:
    """Lazily-built basis files shared by tests in this run."""
    workdir: str | None = None
    basis_bmw3_fp: str | None = None
    basis_bmw3_q: str | None = None
    basis_jordan3_fp: str | None = None
    basis_jordan3_q: str | None = None


def setUpModule() -> None:
    _Fixtures.workdir = tempfile.mkdtemp(prefix="f4ncgb_tests_")
    _Fixtures.basis_bmw3_fp = _emit_and_gb(
        _Fixtures.workdir, n=3, untwist="bigelow", framing_power=1,
        char=P_DEFAULT,
    )
    _Fixtures.basis_bmw3_q = _emit_and_gb(
        _Fixtures.workdir, n=3, untwist="bigelow", framing_power=1, char=0,
    )
    _Fixtures.basis_jordan3_fp = _emit_and_gb(
        _Fixtures.workdir, n=3, untwist="jordan", framing_power=1,
        char=P_DEFAULT,
    )
    _Fixtures.basis_jordan3_q = _emit_and_gb(
        _Fixtures.workdir, n=3, untwist="jordan", framing_power=1, char=0,
    )


def tearDownModule() -> None:
    if _Fixtures.workdir is not None:
        shutil.rmtree(_Fixtures.workdir, ignore_errors=True)


# --- Tests of the core utilities. -------------------------------------------

class TestParsers(unittest.TestCase):
    def test_fp_parser_recovers_lead_and_total_count(self) -> None:
        polys = core.parse_basis_Fp(_Fixtures.basis_bmw3_fp)
        self.assertEqual(len(polys), 30)  # known BMW_3 basis size
        leads = {lm for lm, _ in polys}
        self.assertIn(("x1", "y1"), leads)  # invertibility relation
        # Every polynomial begins with its leading monomial.
        for lm, terms in polys:
            self.assertEqual(terms[0][1], lm)

    def test_q_parser_returns_fractions(self) -> None:
        polys = core.parse_basis_Q(_Fixtures.basis_bmw3_q)
        self.assertEqual(len(polys), 30)
        for _, terms in polys:
            for coef, _ in terms:
                self.assertIsInstance(coef, Fraction)

    def test_leading_only_parser_matches_full(self) -> None:
        full = core.parse_basis_Fp(_Fixtures.basis_bmw3_fp)
        lm_only = core.parse_leading_monomials(_Fixtures.basis_bmw3_fp)
        self.assertEqual([lm for lm, _ in full], lm_only)


class TestAhoCorasick(unittest.TestCase):
    def test_match_pat_propagation_through_failure_chain(self) -> None:
        # Toy alphabet {a, b}, leading monomials {(a, b), (b, a, b)}.
        # Reading "a, a, b" matches (a, b) at position 2; reading "b, a, b"
        # matches (b, a, b) at position 3 and (a, b) at position 3 via
        # failure-link propagation.
        variables = ["a", "b"]
        lms = [("a", "b"), ("b", "a", "b")]
        delta, is_match, match_pat, _ = core.build_aho_corasick(lms, variables)
        # Walk "aab" — final state should be a match.
        state = 0
        for v in ("a", "a", "b"):
            state = delta[(state, v)]
        self.assertTrue(is_match[state])
        self.assertEqual(match_pat[state], ("a", "b"))


class TestStandardMonomials(unittest.TestCase):
    def test_bmw3_has_15_standard_monomials(self) -> None:
        polys = core.parse_basis_Fp(_Fixtures.basis_bmw3_fp)
        variables = core.collect_variables(polys)
        lms = [lm for lm, _ in polys]
        delta, is_match, _, _ = core.build_aho_corasick(lms, variables)
        standard = core.enumerate_standard_monomials(delta, is_match, variables)
        self.assertIsNotNone(standard)
        self.assertEqual(len(standard), 15)
        self.assertEqual(standard[0], ())  # the empty monomial


class TestReduction(unittest.TestCase):
    """Reduce known polynomials and check the result matches the algebra
    structure of BMW_3."""

    def _setup(self, basis_path: str, ring: str):
        polys = (core.parse_basis_Fp(basis_path) if ring == "Fp"
                 else core.parse_basis_Q(basis_path))
        variables = core.collect_variables(polys)
        lms = [lm for lm, _ in polys]
        delta, is_match, match_pat, _ = core.build_aho_corasick(lms, variables)
        standard = core.enumerate_standard_monomials(delta, is_match, variables)
        mon_idx = {m: i for i, m in enumerate(standard)}
        if ring == "Fp":
            tail = core.lm_to_tail_Fp(polys, P_DEFAULT)
        else:
            tail = core.lm_to_tail_Q(polys)
        return polys, variables, delta, is_match, match_pat, standard, mon_idx, tail

    def test_unit_reduces_to_itself_fp(self) -> None:
        _, _, d, im, mp, _, mon_idx, tail = self._setup(
            _Fixtures.basis_bmw3_fp, "Fp")
        # Every generator x_j is in the standard-monomial basis at BMW_3.
        v = core.reduce_to_basis_Fp(
            [(1, ("x1",))], mon_idx, tail, d, im, mp, P_DEFAULT)
        self.assertEqual(v, {mon_idx[("x1",)]: 1})

    def test_invertibility_xy_reduces_to_one_fp(self) -> None:
        _, _, d, im, mp, _, mon_idx, tail = self._setup(
            _Fixtures.basis_bmw3_fp, "Fp")
        # x1*y1 should reduce to the empty monomial (= 1) with coef 1.
        v = core.reduce_to_basis_Fp(
            [(1, ("x1", "y1"))], mon_idx, tail, d, im, mp, P_DEFAULT)
        self.assertEqual(v, {mon_idx[()]: 1})

    def test_invertibility_xy_reduces_to_one_q(self) -> None:
        _, _, d, im, mp, _, mon_idx, tail = self._setup(
            _Fixtures.basis_bmw3_q, "Q")
        v = core.reduce_to_basis_Q(
            [(Fraction(1), ("x1", "y1"))], mon_idx, tail, d, im, mp)
        self.assertEqual(v, {mon_idx[()]: Fraction(1)})


# --- Integration tests of the consumer scripts. -----------------------------

def _run_dim_aho(basis: str) -> int:
    """Invoke ``compute_dim_aho.py`` and parse the reported total dim."""
    out = subprocess.check_output(
        ["python3", os.path.join(HERE, "compute_dim_aho.py"),
         basis, "--max-deg", "20"],
        text=True,
    )
    for line in out.splitlines():
        if "Quotient dimension" in line:
            return int(line.rsplit(":", 1)[1].strip())
    raise AssertionError(f"Could not parse dim from compute_dim_aho output:\n{out}")


def _run_semisimple_Q(basis: str) -> tuple[int, int]:
    """Invoke ``semisimple_Q.py`` and return (N, rank T)."""
    out = subprocess.check_output(
        ["python3", os.path.join(HERE, "semisimple_Q.py"),
         basis, "--max-dim", "200"],
        text=True,
    )
    N = rank = None
    for line in out.splitlines():
        if line.strip().startswith("N         ="):
            N = int(line.split("=")[1].strip())
        if line.strip().startswith("rank(T)   ="):
            rank = int(line.split("=")[1].split()[0])
    assert N is not None and rank is not None, out
    return N, rank


class TestIntegration(unittest.TestCase):
    def test_bmw3_has_dim_15(self) -> None:
        self.assertEqual(_run_dim_aho(_Fixtures.basis_bmw3_fp), 15)

    def test_bmw3_is_semisimple_over_q(self) -> None:
        N, rank = _run_semisimple_Q(_Fixtures.basis_bmw3_q)
        self.assertEqual(N, 15)
        self.assertEqual(rank, 15)  # det T ≠ 0 ⇒ full rank

    def test_jordan3_has_dim_24(self) -> None:
        self.assertEqual(_run_dim_aho(_Fixtures.basis_jordan3_fp), 24)

    def test_jordan3_is_non_semisimple_over_q(self) -> None:
        N, rank = _run_semisimple_Q(_Fixtures.basis_jordan3_q)
        self.assertEqual(N, 24)
        self.assertEqual(rank, 15)  # rank deficit = 9 ⇒ non-semisimple


if __name__ == "__main__":
    unittest.main(verbosity=2)
