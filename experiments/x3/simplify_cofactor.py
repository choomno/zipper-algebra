# ===========================================================================
# B_3 braid normal form.
# Generators (in our 1-based var indexing):
#   sigma_1 = x_1 (var 1)
#   sigma_2 = x_2 (var 2)
#   sigma_1^{-1} = y_1 (var 4)
#   sigma_2^{-1} = y_2 (var 5)
# Delta = sigma_1 sigma_2 sigma_1 = sigma_2 sigma_1 sigma_2.
# Delta acts by conjugation as the swap (1 <-> 2) on generators.
#
# We represent every word as (k, positive_word) where the word equals
# Delta^k * positive_word, k in Z, positive_word a word in {1, 2} (1-based
# atoms only: 1 = sigma_1, 2 = sigma_2).
# ===========================================================================

SIGMA1 = 1
SIGMA2 = 2
Y1 = 4
Y2 = 5

POS_OF = {SIGMA1: 1, SIGMA2: 2}   # var index -> generator index (1 or 2)
NEG_OF = {Y1: 1, Y2: 2}            # var index -> generator index (1 or 2)


def swap_pos(pos_word: Tuple[int, ...]) -> Tuple[int, ...]:
    """Apply Delta-conjugation: sigma_1 <-> sigma_2."""
    return tuple(3 - a for a in pos_word)


def word_to_garside_raw(word: Tuple[int, ...]) -> Tuple[int, Tuple[int, ...]]:
    """
    Convert a free word in {x_1, x_2, y_1, y_2} to (k, pos_word) where the
    free-algebra element equals Delta^k * pos_word in B_3.
    Uses sigma_i^{-1} = sigma_{3-i} sigma_i Delta^{-1}, and Delta^{-1}*P =
    swap(P)*Delta^{-1}.

    Algorithm: process letters left-to-right; maintain (k, P).
        result * sigma_i:        P.append(i)
        result * sigma_i^{-1}: P -> swap(P), then append i, append 3-i; k -= 1
    Derivation:
       (Delta^k * P) * sigma_i^{-1}
         = Delta^k * P * (sigma_{3-i} sigma_i) * Delta^{-1}
         = Delta^k * Delta^{-1} * swap(P sigma_{3-i} sigma_i)        [P Delta^{-1} = Delta^{-1} swap(P)]
         = Delta^{k-1} * swap(P) * swap(sigma_{3-i}) * swap(sigma_i)
         = Delta^{k-1} * swap(P) * sigma_i * sigma_{3-i}
    """
    k = 0
    P: List[int] = []
    for g in word:
        if g in POS_OF:
            P.append(POS_OF[g])
        elif g in NEG_OF:
            i = NEG_OF[g]
            # P -> swap(P), append i, then 3-i; k -= 1
            P = [3 - a for a in P]
            P.append(i)
            P.append(3 - i)
            k -= 1
        elif g == 3 or g == 6:
            raise ValueError(f"x_3 / y_3 not supported (var index {g})")
        else:
            raise ValueError(f"Unknown var index {g}")
    return k, tuple(P)


# ===========================================================================
# Positive B_3 normal form: left-greedy Garside.
# B_3^+ generators a=1, b=2 with relation aba = bab.
# Permutation braids (divisors of Delta): {e, a, b, ab, ba, aba=Delta}.
# Left-greedy: split positive word into atoms A_1 A_2 ... where each A_i is
# the *longest* prefix that is a permutation braid (i.e. no letter repeated
# inappropriately). Also, A_i A_{i+1} must be "left-weighted" -- no letter
# can be moved from A_{i+1} into A_i.
#
# Concretely for B_3: an "atom" string in {a,b}* is a perm braid iff its
# length <= 3 and equals one of {e, a, b, ab, ba, aba, bab}. (aba == bab as
# braids, but as a string we'll normalize to "aba" by greedy substitution.)
# ===========================================================================

# Use letters a=1, b=2.

def pos_left_greedy_atoms(pos: Tuple[int, ...]) -> List[Tuple[int, ...]]:
    """
    Split a positive word into a sequence of permutation-braid atoms via
    left-greedy. We use the rewriting system on positive words:
       a a    -> a a    (idempotent: ok; aa is not a perm braid; aa starts a new atom)
       b b    -> b b
       a b a  -> Delta  (one atom, length 3, = Delta)
       b a b  -> a b a  (normalize bab -> aba)
       a a    -> aa     (two atoms: a | a)
    Algorithm (simpler): one pass + a confluent normalization step.

    Actually we use a different concrete plan: directly compute the Garside
    normal form by repeated application of the rewriting:
       Repeat:
         (1) substitute "bab" -> "aba" (normalize Delta)
         (2) substitute "abab" -> "aba b" then "baba" -> "abab" -> "abab"... etc.
       Hmm: better to use a known small-DFA solution.

    For B_3 positive monoid, the left-greedy Garside form is known to coincide
    with: write the word as a sequence of "blocks" of the form a^* b^*  or
    b^* a^* alternating. ... Actually let's just hash by the abelianization
    plus a "shape" -- no, that's not faithful.

    We implement the following CORRECT but pragmatic algorithm:
      (a) Repeatedly rewrite "bab" -> "aba" (left-to-right scan).
      (b) After step (a), the word has no "bab" substring. Lemma: such a word
          is in left-greedy Garside normal form for B_3^+ once additionally we
          do not have "abab" appearing... actually "abab" doesn't appear
          either if we keep rewriting.
    Let's just verify by examples; if it fails, fall back to brute-force.
    """
    # Step (a): repeatedly rewrite bab -> aba (note: aba and bab equal as
    # braid group elements, but as strings we choose aba as canonical).
    s = list(pos)
    changed = True
    while changed:
        changed = False
        i = 0
        while i + 2 < len(s) + 1:
            if i + 2 < len(s):
                pass
            if i + 2 < len(s) and s[i] == 2 and s[i+1] == 1 and s[i+2] == 2:
                s[i:i+3] = [1, 2, 1]
                changed = True
                # restart scan to be safe
                i = max(0, i - 2)
            else:
                i += 1
    # Now split into permutation-braid atoms left-greedily.
    # In B_3, allowed atom strings are: a, b, ab, ba, aba (=Delta).
    # Greedy: at each position, take the longest prefix in this set.
    atoms: List[Tuple[int, ...]] = []
    i = 0
    n = len(s)
    while i < n:
        # try length 3
        if i + 3 <= n:
            tri = tuple(s[i:i+3])
            if tri == (1, 2, 1):
                atoms.append(tri)
                i += 3
                continue
        # try length 2
        if i + 2 <= n:
            di = tuple(s[i:i+2])
            if di in {(1, 2), (2, 1)}:
                atoms.append(di)
                i += 2
                continue
        # length 1
        atoms.append((s[i],))
        i += 1
    return atoms


def garside_normalize(k: int, pos: Tuple[int, ...]) -> Tuple[int, List[Tuple[int, ...]]]:
    """
    Given (k, pos_word), apply Delta-factorization to push out ALL Delta
    atoms from the positive part. Rule: a Delta atom anywhere in the
    atom-list can be moved to the very left, swapping (sigma_1 <-> sigma_2)
    on every atom to its LEFT. This works because
        A * Delta = Delta * swap(A)
    for any positive atom A (since Delta acts as the swap by conjugation).

    Also, after moving Delta's to the left, we re-split into atoms.

    Then perform left-weighting: an iterative pass that ensures no atom
    A_i can be merged with the next A_{i+1} into a single permutation
    braid (= a single perm braid prefix of length up to 3). This makes
    the form canonical.

    Return (k', atoms') with no Delta atoms and locally left-weighted.
    """
    atoms = pos_left_greedy_atoms(pos)
    # Repeatedly absorb Delta atoms from the right by moving them left.
    changed = True
    while changed:
        changed = False
        # Scan for any Delta atom
        i = 0
        while i < len(atoms):
            if atoms[i] == (1, 2, 1):
                # Swap all atoms to the left of i, remove atoms[i], k += 1
                for j in range(i):
                    atoms[j] = swap_pos(atoms[j])
                del atoms[i]
                k += 1
                changed = True
                # restart scan
                break
            i += 1
        if changed:
            continue
        # Left-weighting: re-flatten and re-split if necessary
        # If two adjacent atoms can be merged into a longer permutation
        # braid (i.e. the concatenated string still parses as <= 3-letter
        # perm braid greedily), merge them. After bab->aba normalization,
        # the only such case is: atom (i,)*(j,) with i!=j -> (i,j) is OK
        # left-greedy already.
        # We re-flatten and re-split to catch leftover non-canonical
        # adjacencies introduced by Delta moves.
        flat = []
        for a in atoms:
            flat.extend(a)
        # re-apply bab -> aba
        s = list(flat)
        ch = True
        while ch:
            ch = False
            i2 = 0
            while i2 + 2 < len(s):
                if s[i2] == 2 and s[i2+1] == 1 and s[i2+2] == 2:
                    s[i2:i2+3] = [1, 2, 1]
                    ch = True
                    i2 = max(0, i2 - 2)
                else:
                    i2 += 1
        new_atoms = pos_left_greedy_atoms(tuple(s))
        if new_atoms != atoms:
            atoms = new_atoms
            changed = True
    return k, atoms


def normalize_word(word: Tuple[int, ...]) -> Tuple[int, Tuple[Tuple[int, ...], ...]]:
    """Return canonical (k, atoms) tuple for hashing."""
    k0, pos0 = word_to_garside_raw(word)
    k1, atoms = garside_normalize(k0, pos0)
    return k1, tuple(atoms)


# ===========================================================================
# Build a FREE-ALGEBRA representative from a canonical (k, atoms) tuple.
# Conventions:
#   Delta = x_1*x_2*x_1     (atoms == [(1,2,1), ...])
#   Delta^{-1} = y_1*y_2*y_1
#   atom (1,) -> x_1, (2,) -> x_2, (1,2) -> x_1*x_2, (2,1) -> x_2*x_1,
#   atom (1,2,1) -> x_1*x_2*x_1
# When k > 0, representative = (Delta)^k * atoms_concat
# When k < 0, representative = (Delta^{-1})^{-k} * atoms_concat
# When k = 0, representative = atoms_concat
# ===========================================================================

DELTA_WORD: Tuple[int, ...] = (SIGMA1, SIGMA2, SIGMA1)            # x_1*x_2*x_1
DELTA_INV_WORD: Tuple[int, ...] = (Y1, Y2, Y1)                    # y_1*y_2*y_1

# Sanity: y_1*y_2*y_1 equals Delta^{-1}? We have y_i = sigma_i^{-1}. So
# y_1*y_2*y_1 = (sigma_1 sigma_2 sigma_1)^{-1} = Delta^{-1}. Yes.

def atom_to_word(a: Tuple[int, ...]) -> Tuple[int, ...]:
    """atom uses generator indices 1,2 -- map to var indices SIGMA1=1, SIGMA2=2."""
    return tuple(SIGMA1 if x == 1 else SIGMA2 for x in a)


def canonical_word(k: int, atoms: Tuple[Tuple[int, ...], ...]) -> Tuple[int, ...]:
    """
    Build a FREE-ALGEBRA word representing Delta^k * (atoms concatenation).
    Note: This word may differ from the input word as a free-algebra element
    (since Delta^k atom_chain != original word in the FREE algebra in general).
    But as an element of the group algebra Q(q,t)[B_3] it is identical.
    """
    out: List[int] = []
    if k > 0:
        out.extend(DELTA_WORD * k)
    elif k < 0:
        out.extend(DELTA_INV_WORD * (-k))
    for a in atoms:
        out.extend(atom_to_word(a))
    return tuple(out)


