#!/usr/bin/env python3
"""
Simplify the 1077-tuple X_3 cofactor at n=4 over Q(q,t) by normalizing every
multiplier as an element of the braid group B_3 (= the sub-group of B_4
generated by sigma_1, sigma_2, which is all that appears in S[3][1]).

Strategy
--------
1. Parse the 1077-tuple compressed cofactor.
2. For each tuple (c, L, i, R):
   - Compute (i_left_k, L_pos_word) := B_3 Garside form of L
     (where L = Delta^{i_left_k} * L_pos_word, L_pos_word in left-greedy
     positive Garside normal form).
   - Same for R.
   - Replace L by the canonical free-algebra representative of (i_left_k, L_pos_word):
       canonical(k, P) = Delta_word^k * P (with k>=0)
                       = (if k<0) Delta_inv_word^|k| * P
     where Delta_word = x_1*x_2*x_1, Delta_inv_word = y_1*y_2*y_1 (= Delta^{-1}).
3. Merge tuples that share (canonical(L), i, canonical(R)) by summing coefficients.
4. For bookkeeping indices i in {0,1,2,3,6}, the canonical(L)*R_i*canonical(R) is
   exactly zero modulo the braid-group bookkeeping (since R_0 = x_1 y_1 - 1, ...
   are bookkeeping for invertibility, and R_6 is the braid relation).
   We KEEP these tuples in the output as "residual" bookkeeping items but they
   indicate genuine non-vanishing contribution in the FREE algebra.
   In the GROUP ALGEBRA Q(q,t)[B_3], they are identically zero.
5. The expected outcome: after canonicalization and merging, the surviving
   slider tuples (i in {22,25,26,28}) represent the cofactor in the group-algebra
   sense. The bookkeeping tuples should sum to ZERO modulo the canonical
   substitutions Delta_word^k = canonical free-alg representative.

Verification (acceptance criterion (a))
---------------------------------------
The output tuples, when re-expanded in the free algebra (each canonical(L) is
just a free-algebra word: x's and y's), must sum to X_3 EXACTLY in the free
algebra Q(q,t)<x1,x2,x3,y1,y2,y3>. We re-use symbolic_identity_check.py
plumbing for that.
"""

