def parse_compressed(path: str):
    """Yield (left_mon_tuple, idx, right_mon_tuple, num_qtpoly, den_4tuple)."""
    with open(path) as f:
        for ln in f:
            s = ln.strip()
            if not s or s.startswith("#"):
                continue
            parsed = parse_cofactor_line(ln)
            yield parsed


def den_to_qtpoly(den_4t, qpow, tpow, qm1pow, tpq2pow) -> "QTPoly":
    a_q, b_t, k1, k2 = den_4t
    return qt_mul(qt_mul(qt_mul(qpow[a_q], tpow[b_t]), qm1pow[k1]), tpq2pow[k2])


